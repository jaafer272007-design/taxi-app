import { IsISO8601, IsOptional, IsString, MinLength } from 'class-validator';

/**
 * «أبلغنا أنك تريد هذا المسار» — نقرة واحدة، بلا نموذج.
 *
 * الحمولة الصغيرة مقصودة وهي جوهر الميزة لا اختصار فيها: الراكب في حالة
 * فارغة وعلى وشك المغادرة، وكل حقل إضافي يطلب منه شيئاً هو سبب إضافي ألّا
 * يخبرنا أصلاً — وعندها نبقى نخمّن.
 *
 * `requestedFor` سياق لا قيد: **التاريخ الذي كان يبحث عنه**، إن كان قد حدّده.
 * لا يدخل في الـdedupe ولا في الفان-آوت (الإشعار عن الممر، لا عن يوم بعينه):
 * راكب يريد النجف↔كربلاء يوم الخميس يريدها يوم الأربعاء أيضاً على الأغلب،
 * ورفض إشعاره لأن الرحلة في يوم مجاور يهدر الإشارة كلها.
 */
export class CreateRouteRequestDto {
  @IsString({ message: 'الممر مطلوب.' })
  @MinLength(1, { message: 'الممر مطلوب.' })
  corridorId!: string;

  @IsOptional()
  @IsISO8601({}, { message: 'تاريخ غير صالح.' })
  requestedFor?: string;
}
